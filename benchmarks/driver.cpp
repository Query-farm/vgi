static std::string Json(const std::string &s) {
    std::ostringstream out;
    out << '"';
    for (unsigned char c : s) {
        if (c == '"' || c == '\\') out << '\\' << c;
        else if (c < 32) out << "\\u" << std::hex << std::setw(4) << std::setfill('0') << unsigned(c);
        else out << c;
    }
    out << '"';
    return out.str();
}

static double Seconds(timeval t) { return t.tv_sec + t.tv_usec / 1e6; }

// Optional diagnostic commands, never called by ordinary benchmark runs.
// DuckDB's allocator is prefixed; ArrowBuffer/new can use glibc separately.
extern "C" int duckdb_je_mallctl(const char *, void *, size_t *, void *, size_t) __attribute__((weak));
static std::string AllocatorStats() {
    std::ostringstream out;
    out << "{\"glibc\":";
#if defined(VGI_BENCH_HAS_MALLINFO2)
    auto m = mallinfo2();
    out << "{\"arena\":" << m.arena << ",\"uordblks\":" << m.uordblks
        << ",\"fordblks\":" << m.fordblks << ",\"hblkhd\":" << m.hblkhd << "}";
#else
    out << "null";
#endif
    out << ",\"jemalloc\":";
    uint64_t epoch = 1;
    if (duckdb_je_mallctl && duckdb_je_mallctl("epoch", nullptr, nullptr, &epoch, sizeof(epoch)) == 0) {
        out << "{";
        const char *keys[] = {"allocated", "active", "resident", "retained"};
        for (int i = 0; i < 4; ++i) {
            size_t value = 0, size = sizeof(value);
            if (i) out << ",";
            out << Json(keys[i]) << ":";
            if (duckdb_je_mallctl((std::string("stats.") + keys[i]).c_str(), &value, &size, nullptr, 0) == 0)
                out << value;
            else out << "null"; // stats can be disabled at build time
        }
        out << "}";
    } else out << "null";
    out << "}";
    return out.str();
}

static std::string ArrowAllocatorStats(const std::string &extension_path, int mode) {
    // RTLD_NOLOAD guarantees that this observes the already-loaded extension,
    // including after database close, rather than loading a fresh Arrow pool.
    auto handle = dlopen(extension_path.c_str(), RTLD_NOW | RTLD_NOLOAD);
    if (!handle) throw std::runtime_error("Arrow probe requires the loaded extension's absolute path");
    auto probe = reinterpret_cast<const char *(*)(int)>(dlsym(handle, "vgi_benchmark_arrow_pool"));
    if (!probe) {
        dlclose(handle);
        throw std::runtime_error("extension was not built with VGI_BENCH_ARROW_PROBE=ON");
    }
    std::string result = probe(mode);
    dlclose(handle);
    return result;
}

// Benchmark-only source: one payload copy into DuckDB's string heap, without
// SQL concatenation temporaries. Exact chunk sizes isolate batch memory from
// total table length. The generated bytes match workloads.py's SQL source.
struct StringSource {
    idx_t rows, columns, width, batch_rows, null_every;
};
struct StringSourceState {
    idx_t next = 0;
    std::string value;
};
static std::atomic<uint64_t> source_batches {0}, source_rows {0}, source_max_bytes {0};

static void BindStrings(duckdb_bind_info info) {
    try {
        uint64_t args[5];
        for (idx_t i = 0; i < 5; ++i) {
            auto value = duckdb_bind_get_parameter(info, i);
            bool is_null = duckdb_is_null_value(value);
            auto number = duckdb_get_int64(value);
            duckdb_destroy_value(&value);
            if (is_null) throw std::runtime_error("bench_strings parameters must not be NULL");
            if (number < 0) throw std::runtime_error("bench_strings parameters must be nonnegative");
            args[i] = static_cast<uint64_t>(number);
        }
        if (args[0] < 1 || args[0] > 1000000000000ULL || args[1] < 1 || args[1] > 2048 ||
            args[2] < 24 || args[2] > 1048576 || args[3] < 1 || args[3] > duckdb_vector_size())
            throw std::runtime_error("invalid bench_strings rows, columns, width or batch_rows");
        auto data = std::unique_ptr<StringSource>(new StringSource {args[0], args[1], args[2], args[3], args[4]});
        auto type = duckdb_create_logical_type(DUCKDB_TYPE_VARCHAR);
        for (idx_t c = 0; c < data->columns; ++c)
            duckdb_bind_add_result_column(info, ("c" + std::to_string(c)).c_str(), type);
        duckdb_destroy_logical_type(&type);
        duckdb_bind_set_cardinality(info, data->rows, true);
        duckdb_bind_set_bind_data(info, data.release(), [](void *p) { delete static_cast<StringSource *>(p); });
    } catch (const std::exception &e) { duckdb_bind_set_error(info, e.what()); }
}

static void InitStrings(duckdb_init_info info) {
    try {
        auto &data = *static_cast<StringSource *>(duckdb_init_get_bind_data(info));
        auto state = std::unique_ptr<StringSourceState>(new StringSourceState);
        state->value.assign(data.width, 'x');
        duckdb_init_set_max_threads(info, 1);
        duckdb_init_set_init_data(info, state.release(), [](void *p) { delete static_cast<StringSourceState *>(p); });
    } catch (const std::exception &e) { duckdb_init_set_error(info, e.what()); }
}

static void GenerateStrings(duckdb_function_info info, duckdb_data_chunk output) {
    try {
        auto &data = *static_cast<StringSource *>(duckdb_function_get_bind_data(info));
        auto &state = *static_cast<StringSourceState *>(duckdb_function_get_init_data(info));
        auto count = std::min(data.batch_rows, data.rows - state.next);
        for (idx_t c = 0; c < data.columns; ++c) {
            auto vector = duckdb_data_chunk_get_vector(output, c);
            uint64_t *validity = nullptr;
            if (data.null_every) {
                duckdb_vector_ensure_validity_writable(vector);
                validity = duckdb_vector_get_validity(vector);
            }
            for (idx_t r = 0; r < count; ++r) {
                auto row = state.next + r;
                bool valid = !data.null_every || row % data.null_every != 0;
                if (validity) duckdb_validity_set_row_validity(validity, r, valid);
                if (!valid) continue;
                char suffix[25];
                std::snprintf(suffix, sizeof(suffix), "%020llu%04llu",
                              static_cast<unsigned long long>(row), static_cast<unsigned long long>(c));
                state.value.replace(data.width - 24, 24, suffix, 24);
                duckdb_vector_assign_string_element_len(vector, r, state.value.data(), state.value.size());
            }
        }
        duckdb_data_chunk_set_size(output, count);
        state.next += count;
        if (count) {
            source_batches.fetch_add(1);
            source_rows.fetch_add(count);
            uint64_t bytes = count * data.columns * data.width; // logical, before nulls/offsets
            auto maximum = source_max_bytes.load();
            while (maximum < bytes && !source_max_bytes.compare_exchange_weak(maximum, bytes)) {}
        }
    } catch (const std::exception &e) { duckdb_function_set_error(info, e.what()); }
}

static void RegisterStrings(duckdb_connection con) {
    auto function = duckdb_create_table_function();
    duckdb_table_function_set_name(function, "bench_strings");
    auto type = duckdb_create_logical_type(DUCKDB_TYPE_BIGINT);
    for (int i = 0; i < 5; ++i) duckdb_table_function_add_parameter(function, type);
    duckdb_destroy_logical_type(&type);
    duckdb_table_function_set_bind(function, BindStrings);
    duckdb_table_function_set_init(function, InitStrings);
    duckdb_table_function_set_function(function, GenerateStrings);
    auto status = duckdb_register_table_function(con, function);
    duckdb_destroy_table_function(&function);
    if (status != DuckDBSuccess) throw std::runtime_error("cannot register bench_strings");
}

int main() {
    duckdb_database db = nullptr;
    duckdb_connection con = nullptr;
    duckdb_config config = nullptr;
    try {
        duckdb_create_config(&config);
        if (duckdb_set_config(config, "allow_unsigned_extensions", "true") == DuckDBError)
            throw std::runtime_error("cannot enable unsigned extensions");
        char *error = nullptr;
        if (duckdb_open_ext(nullptr, &db, config, &error) == DuckDBError) {
            std::string message = error ? error : "database open failed";
            duckdb_free(error);
            throw std::runtime_error(message);
        }
        duckdb_destroy_config(&config);
        if (duckdb_connect(db, &con) == DuckDBError) throw std::runtime_error("connect failed");
        RegisterStrings(con);
        std::cout << "{\"event\":\"ready\",\"pid\":" << getpid()
                  << ",\"engine_version\":" << Json(duckdb_library_version()) << "}" << std::endl;
        std::string line;
        while (std::getline(std::cin, line)) {
            // op TAB expected scalar (empty for unchecked setup) TAB SQL.
            auto a = line.find('\t'), b = line.find('\t', a + 1);
            if (a == std::string::npos || b == std::string::npos) throw std::runtime_error("invalid command");
            auto op = line.substr(0, a), expected = line.substr(a + 1, b - a - 1), sql = line.substr(b + 1);
            source_batches = 0;
            source_rows = 0;
            source_max_bytes = 0;
            rusage before {}, after {};
            getrusage(RUSAGE_SELF, &before);
            auto start = std::chrono::steady_clock::now();
            std::string value;
            if (op == "allocator") {
                value = AllocatorStats();
            } else if (op == "arrow_allocator" || op == "release_arrow" || op == "schema_reuse") {
                value = ArrowAllocatorStats(sql, op == "schema_reuse" ? 2 : op == "release_arrow" ? 1 : 0);
            } else if (op == "trim_glibc") {
#if defined(__GLIBC__)
                value = std::to_string(malloc_trim(0));
#else
                throw std::runtime_error("trim_glibc requires glibc");
#endif
            } else if (op == "close") {
                duckdb_disconnect(&con);
                duckdb_close(&db);
            } else if ((op == "query" || op == "inspect" || op == "exec" || op == "plan" ||
                        op == "expect_error" || op == "interrupt") && con) {
                duckdb_result result {};
                // Interrupt only this connection. Join before accepting another
                // command so a late timer can never cancel the recovery query.
                std::mutex timer_mutex;
                std::condition_variable timer_cv;
                bool query_done = false;
                std::thread timer;
                if (op == "interrupt") {
                    auto delay_ms = std::stoll(expected);
                    if (delay_ms < 1 || delay_ms > 60000) throw std::runtime_error("invalid interrupt delay");
                    timer = std::thread([&]() {
                        std::unique_lock<std::mutex> lock(timer_mutex);
                        if (!timer_cv.wait_for(lock, std::chrono::milliseconds(delay_ms), [&]() { return query_done; }))
                            duckdb_interrupt(con);
                    });
                }
                auto state = duckdb_query(con, sql.c_str(), &result);
                if (timer.joinable()) {
                    { std::lock_guard<std::mutex> lock(timer_mutex); query_done = true; }
                    timer_cv.notify_one();
                    timer.join();
                }
                if (state == DuckDBError) {
                    std::string message = duckdb_result_error(&result);
                    duckdb_destroy_result(&result);
                    if (op == "expect_error" && !expected.empty() && message.find(expected) != std::string::npos) {
                        value = message;
                    } else if (op == "interrupt" && message.find("Interrupt") != std::string::npos) {
                        value = message;
                    } else {
                        throw std::runtime_error(message);
                    }
                } else if (op == "expect_error" || op == "interrupt") {
                    duckdb_destroy_result(&result);
                    throw std::runtime_error("expected query failure did not occur");
                }
                if (state != DuckDBError && (op == "query" || op == "inspect")) {
                    if (duckdb_column_count(&result) != 1 || duckdb_row_count(&result) != 1 ||
                        duckdb_value_is_null(&result, 0, 0)) {
                        duckdb_destroy_result(&result);
                        throw std::runtime_error("workload must return one non-null checksum");
                    }
                    char *text = duckdb_value_varchar(&result, 0, 0);
                    value = text;
                    duckdb_free(text);
                }
                if (state != DuckDBError && op == "plan") {
                    for (idx_t row = 0; row < duckdb_row_count(&result); row++) {
                        char *text = duckdb_value_varchar(&result, duckdb_column_count(&result) - 1, row);
                        if (text) { value += text; value += '\n'; duckdb_free(text); }
                    }
                }
                if (state != DuckDBError) duckdb_destroy_result(&result); // release belongs to measured query
                if (op == "query" && value != expected)
                    throw std::runtime_error("checksum mismatch: expected " + expected + ", got " + value);
            } else throw std::runtime_error("invalid operation or closed connection");
            auto elapsed = std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
            getrusage(RUSAGE_SELF, &after);
            std::cout << std::setprecision(12)
                      << "{\"event\":\"result\",\"wall_s\":" << elapsed
                      << ",\"host_user_s\":" << Seconds(after.ru_utime) - Seconds(before.ru_utime)
                      << ",\"host_system_s\":" << Seconds(after.ru_stime) - Seconds(before.ru_stime)
                      << ",\"host_lifetime_peak_rss_bytes\":" << after.ru_maxrss * 1024LL
                      << ",\"host_minor_faults\":" << after.ru_minflt - before.ru_minflt
                      << ",\"host_major_faults\":" << after.ru_majflt - before.ru_majflt
                      << ",\"source_batches\":" << source_batches.load()
                      << ",\"source_rows\":" << source_rows.load()
                      << ",\"source_max_batch_bytes\":" << source_max_bytes.load()
                      << ",\"checksum\":" << Json(value) << "}" << std::endl;
            // Stay alive after close so the observer can measure allocator
            // retention after both the connection and database are destroyed.
        }
    } catch (const std::exception &e) {
        std::cout << "{\"event\":\"error\",\"message\":" << Json(e.what()) << "}" << std::endl;
        if (con) duckdb_disconnect(&con);
        if (db) duckdb_close(&db);
        if (config) duckdb_destroy_config(&config);
        return 1;
    }
    if (con) duckdb_disconnect(&con);
    if (db) duckdb_close(&db);
    return 0;
}
