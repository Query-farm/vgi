// Small Linux benchmark host. SQL runs in one connection, so warm-up and
// release measurements observe the same database, worker pool and allocator.
#include "duckdb.h"
#include <algorithm>
#include <atomic>
#include <chrono>
#include <condition_variable>
#include <cstdio>
#include <dlfcn.h>
#include <iomanip>
#include <iostream>
#include <memory>
#include <mutex>
#if defined(__GLIBC__)
#include <malloc.h>
#if __GLIBC_PREREQ(2, 33)
#define VGI_BENCH_HAS_MALLINFO2
#endif
#endif
#include <sstream>
#include <stdexcept>
#include <string>
#include <sys/resource.h>
#include <thread>
