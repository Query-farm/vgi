strings += "\n" + literal("The reported query: GROUP BY ALL over a NOT LIKE filter", f"SELECT series, sum(n) FROM {T} WHERE series NOT LIKE '%15M' GROUP BY ALL ORDER BY 2 DESC, 1;", "TI")
